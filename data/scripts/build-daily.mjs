/**
 * Chooses the verses the start screen shows, one a day.
 *
 * A verse picked at random from the whole Bible is usually a line of a genealogy or a
 * measurement of the tabernacle, which is no way to open the app. Picking the verses by
 * hand would mean this file was one person's taste in Scripture.
 *
 * So the choice is made by the text itself. The Treasury of Scripture Knowledge spent
 * two centuries recording which verses the rest of Scripture echoes, quotes and answers,
 * and a verse many other verses point at is one the tradition has already judged
 * significant. Ranking by how often a verse is cited gives a defensible list that nobody
 * here had to curate: comfort and judgment both, in whatever proportion the citations
 * fall.
 *
 * Writes app/src/lib/daily.generated.ts. Run through `npm run data:build`.
 */

import { DatabaseSync } from 'node:sqlite';
import { writeFile } from 'node:fs/promises';

/** One a day for a leap year, so a year can pass before any verse comes round again. */
const WANTED = 366;

/**
 * Long enough to say something, short enough to read on opening the app. Below this a
 * verse is usually a fragment ("Jesus wept." is the exception, not the rule); above it
 * the start screen turns into a page of text.
 */
const SHORTEST = 50;
const LONGEST = 320;

export function chooseDaily(db, wanted = WANTED) {
  const ranked = db
    .prepare(
      `SELECT c.to_book AS bookId, c.to_chapter AS chapter, c.to_verse AS verse,
              COUNT(*) AS cited,
              (SELECT text FROM verses
                WHERE book_id = c.to_book AND chapter = c.to_chapter AND verse = c.to_verse) AS text
         FROM cross_references c
        WHERE c.to_last = c.to_verse
        GROUP BY c.to_book, c.to_chapter, c.to_verse
        ORDER BY cited DESC, c.to_book, c.to_chapter, c.to_verse
        LIMIT ?`,
    )
    .all(wanted * 2);

  const chosen = ranked
    .filter((row) => row.text && row.text.length >= SHORTEST && row.text.length <= LONGEST)
    .slice(0, wanted);

  // Reading order, not citation order: the list is walked by date, and a year that runs
  // Genesis to Revelation is a year that goes somewhere.
  return chosen
    .map(({ bookId, chapter, verse }) => [bookId, chapter, verse])
    .sort((a, b) => a[0] - b[0] || a[1] - b[1] || a[2] - b[2]);
}

export async function buildDaily(dbPath, outPath) {
  const db = new DatabaseSync(dbPath);
  const verses = chooseDaily(db);

  const rows = verses.map(([b, c, v]) => `  [${b}, ${c}, ${v}],`).join('\n');
  const file = `/**
 * The verse the start screen opens on, one for each day of the year.
 *
 * Generated by data/scripts/build-daily.mjs — do not edit by hand.
 *
 * These are the ${verses.length} verses the rest of Scripture cites most often, by the
 * reckoning of the Treasury of Scripture Knowledge, in reading order. Nobody chose them
 * by taste; they are what the cross-references point at. Only the reference is kept, so
 * the words come from whichever edition is being read, through the same path as the
 * rest of the text.
 */

/** [book, chapter, verse] */
export type DailyVerse = readonly [number, number, number];

export const DAILY_VERSES: readonly DailyVerse[] = [
${rows}
];
`;

  await writeFile(outPath, file, 'utf8');
  return verses.length;
}
